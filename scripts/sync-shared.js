// Copies the import-free weather rules into the Edge Functions folder (Deno can't
// import from src/). Run `npm run sync-shared` after editing src/engine/weather-rules.ts.
const fs = require('fs');
const path = require('path');

const HEADER = '// GENERATED by scripts/sync-shared.js from src/engine/weather-rules.ts. Do not edit here.\n';
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src/engine/weather-rules.ts'), 'utf8');
fs.writeFileSync(path.join(root, 'supabase/functions/_shared/weather-rules.ts'), HEADER + src);
console.log('supabase/functions/_shared/weather-rules.ts updated');
