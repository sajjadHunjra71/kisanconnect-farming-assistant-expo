// Copies the pure engine files the Edge Functions need into supabase/functions/_shared/
// (Deno can't import from src/ and needs explicit .ts extensions).
// Run `npm run sync-shared` after editing any of FILES; a unit test fails if a copy is stale.
const fs = require('fs');
const path = require('path');

const FILES = ['dates.ts', 'crops-data.ts', 'crop-calendar.ts', 'weather-rules.ts'];
const HEADER = (f) => `// GENERATED by scripts/sync-shared.js from src/engine/${f}. Do not edit here.\n`;

/** Same text, with relative imports made Deno-friendly ('./x' → './x.ts'). */
function toDeno(src) {
  return src.replace(/from '(\.\/[^']+?)(?<!\.ts)'/g, "from '$1.ts'");
}

function build(root, f) {
  return HEADER(f) + toDeno(fs.readFileSync(path.join(root, 'src/engine', f), 'utf8'));
}

module.exports = { FILES, build };

if (require.main === module) {
  const root = path.join(__dirname, '..');
  for (const f of FILES) {
    fs.writeFileSync(path.join(root, 'supabase/functions/_shared', f), build(root, f));
    console.log(`supabase/functions/_shared/${f} updated`);
  }
}
