// Copies src/engine (except tests) to supabase/functions/_shared/engine for the Edge
// Functions (Deno can't import from src/ and needs explicit .ts extensions).
// Run `npm run sync-engine` after editing the engine; a unit test fails if a copy is stale.
const fs = require('fs');
const path = require('path');

const HEADER = (f) => `// GENERATED by scripts/sync-engine.js from src/engine/${f}. Do not edit here; run \`npm run sync-engine\`.\n`;

function engineFiles(root) {
  return fs.readdirSync(path.join(root, 'src/engine')).filter((f) => f.endsWith('.ts')).sort();
}

/** Same text, relative imports made Deno-friendly ('./x' → './x.ts'). */
function build(root, f) {
  const src = fs.readFileSync(path.join(root, 'src/engine', f), 'utf8');
  return HEADER(f) + src.replace(/(from\s+|import\s*\(\s*)'(\.\/[\w-]+)'/g, "$1'$2.ts'");
}

module.exports = { engineFiles, build };

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const out = path.join(root, 'supabase/functions/_shared/engine');
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  for (const f of engineFiles(root)) fs.writeFileSync(path.join(out, f), build(root, f));
  console.log(`copied ${engineFiles(root).length} engine files to supabase/functions/_shared/engine`);
}
